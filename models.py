def confidence_from_score(score: int, max_score: int) -> str:
    """
    Standardized confidence banding shared by all detectors (TASK-172, audit
    items 12/19): a setup is HIGH confidence when it scores at least 60% of its
    detector's score matrix, MEDIUM otherwise. Previously each detector used
    its own inconsistent bar (breakout 4/6, OI wall and exhaustion 2/4).
    """
    if max_score <= 0:
        return "MEDIUM"
    return "HIGH" if (score / max_score) >= 0.6 else "MEDIUM"


class SetupType(Enum):
    """
    Defines the core setups detected by the ARES system.
    
    Attributes:
        FAILED_BREAKOUT: Triggered when price breaches a level but fails to sustain.
        OI_WALL_REJECTION: Triggered by rejection at strikes with massive fresh Open Interest.
        EXHAUSTION_REVERSAL: Triggered by volume climaxes and indecision at price extremes.
        TREND_CONTINUATION: Triggered by a shallow pullback and resumption within a persistent regime.
    """
    FAILED_BREAKOUT = "FAILED_BREAKOUT"
    OI_WALL_REJECTION = "OI_WALL_REJECTION"
    EXHAUSTION_REVERSAL = "EXHAUSTION_REVERSAL"
    TREND_CONTINUATION = "TREND_CONTINUATION"


class Direction(Enum):
    """
    Indicates the directional bias of the detected trading signal.
    """
    BULLISH = "BULLISH"
    BEARISH = "BEARISH"


