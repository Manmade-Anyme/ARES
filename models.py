@dataclass
class AresSignal:
    """
    The complete trade signal package generated by the ARES Engine.
    
    Attributes:
        setup_type: The strategy that triggered the signal.
        direction: Bullish (CE) or Bearish (PE).
        trigger_price: The spot price at the time of signal generation.
        entry_zone: The suggested price range for trade entry.
        stop_loss: The invalidation level for the trade (Spot reference).
        target_1: First profit target based on structural support/resistance.
        target_2: Second profit target based on further structural levels.
        confidence: Signal quality assessment (HIGH or MEDIUM).
        reasons: Detailed list of technical conditions that met the trigger.
        timestamp: Exact time the signal was generated.
        strike_to_trade: The recommended option strike price.
        option_type: The recommended option contract type (CE/PE).
    """
    setup_type: SetupType
    direction: Direction
    trigger_price: float
    entry_zone: Tuple[float, float]
    stop_loss: float
    target_1: float
    target_2: float
    confidence: str
    reasons: List[str]
    timestamp: datetime
    strike_to_trade: int
    option_type: str
    id: str = field(default_factory=lambda: str(uuid.uuid4()))
    display_id: str = field(default_factory=lambda: f"{random.randint(0, 9999):04d}")
    db_id: Optional[int] = None  # ares_signals row id, set after log_signal; joins trade_analytics to ares_signals
    trade_id: Optional[str] = None  # UUID populated if a trade is executed by PositionManager
    
    @property
    def signal_id(self) -> str:
        """Deprecated: use display_id for presentation or id for database join."""
        return self.display_id
        
    suggested_lots: Optional[int] = None
    option_sl: Optional[float] = None
    option_target: Optional[float] = None
    capital: Optional[float] = None
    option_delta: Optional[float] = None
    option_premium: Optional[float] = None
    risk_pct: Optional[float] = None
    oi_wall_context: Optional[Dict[str, Any]] = None
    market_context: Dict[str, Any] = field(default_factory=dict)
    bracket: Optional[OptionOrderBracket] = None
    options_sizing_status: str = "PENDING"


